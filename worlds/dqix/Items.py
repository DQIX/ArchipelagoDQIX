from enum import Enum
from typing import Dict, NamedTuple, Optional, List

from BaseClasses import ItemClassification, Item
from Options import OptionError
from .options import DQIXOptions, EndBoss


class DQIXItem(Item):
    game = "Dragon Quest IX"
    item_type: str

    def __init__(self, name: str, classification: ItemClassification, code: Optional[int], player: int, item_type: str):
        super(DQIXItem, self).__init__(name, classification, code, player)
        self.item_type = item_type


class ItemType(Enum):
    COMMON_ITEM = "common"
    EQUIPMENT = "equipment"
    EXPERIENCE = "exp"
    GOLD = "gold"
    IMPORTANT_ITEM = "important"
    BOSS_KEY = "boss"


class ItemData(NamedTuple):
    name: str
    code: int
    item_type: ItemType
    classification: ItemClassification


class DQIXItems:
    _item_table: Dict[str, ItemData] = {}

    IMPORTANT_ITEM_IDS = [22042, 22043, 22044, 22158, 22159, 22160, 22162, 22164, 22165, 22166, 22167, 22168, 22169]

    def __init__(self):
        self.progression_items: Dict[str, ItemData] = {x.name: x for x in all_items_dict.values() if x.classification == ItemClassification.progression}
        self.useful_items: Dict[str, ItemData] = {x.name: x for x in all_items_dict.values() if x.classification == ItemClassification.useful}
        self.filler_items: Dict[str, ItemData] = {x.name: x for x in all_items_dict.values() if x.classification == ItemClassification.filler}

    def get_filler_item_names(self):
        return list(self.filler_items.keys())

    def get_active_progression_items(self, options: DQIXOptions) -> List[str]:
        prog_items = []
        allowed_boss_keys = self.get_allowed_boss_keys(options)

        for item_data in self.progression_items.values():
            if item_data.item_type == ItemType.IMPORTANT_ITEM:
                prog_items.append(item_data.name)
            elif item_data.item_type == ItemType.BOSS_KEY and item_data.name in allowed_boss_keys:
                prog_items.append(item_data.name)

        return prog_items

    @staticmethod
    def get_allowed_boss_keys(options: DQIXOptions) -> List[str]:
        if options.end_boss == EndBoss.option_master_of_nuun:
            bosses = ["Hexagoon", "Wight Knight", "Morag", "Ragin' Contagion", "Master of Nu'un"]
        elif options.end_boss == EndBoss.option_greygnarl:
            bosses = ["Hexagoon", "Wight Knight", "Morag", "Ragin' Contagion", "Master of Nu'un", "Lleviathan", "Garth Goyle", "Tyrantula", "Grand Lizzier", "Larstastnaras", "Dreadmaster", "Gadrongo",
                      "Greygnarl"]
        elif options.end_boss == EndBoss.option_corvus:
            bosses = ["Hexagoon", "Wight Knight", "Morag", "Ragin' Contagion", "Master of Nu'un", "Lleviathan", "Garth Goyle", "Tyrantula", "Grand Lizzier", "Larstastnaras", "Dreadmaster", "Gadrongo",
                      "Greygnarl", "Goreham-Hogg (I)",
                      "Hootingham-Gore (I)", "Goresby-Purrvis (I)", "King Godwyn", "Goreham-Hogg (II)", "Hootingham-Gore (II)", "Goresby-Purrvis (II)", "Corvus (I)", "Barbarus", "Corvus (II)"]
        else:
            raise OptionError("Could not determine required Boss Keys: Invalid Option for \"end_boss\": " + options.end_boss)

        return [f"Boss Key: {boss_name}" for boss_name in bosses]


